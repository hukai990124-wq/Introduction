    const storageKey = "hukai-language";
    const locales = { en: "en", zh: "zh-CN", ja: "ja" };
    const switcher = document.querySelector(".language-switcher");
    const buttons = document.querySelectorAll("[data-language]");
    const supported = language => Object.hasOwn(translations, language);

    function applyLanguage(language) {
        const messages = translations[language];
        document.documentElement.lang = locales[language];
        document.querySelectorAll("[data-i18n]").forEach(element => {
            element.textContent = messages[element.dataset.i18n];
        });
        document.querySelectorAll("[data-i18n-alt]").forEach(element => {
            element.alt = messages[element.dataset.i18nAlt];
        });
        switcher.setAttribute("aria-label", messages["language.label"]);
        buttons.forEach(button => {
            button.setAttribute("aria-pressed", String(button.dataset.language === language));
        });
        document.querySelectorAll("[data-language-link]").forEach(link => {
            const url = new URL(link.href);
            url.searchParams.set("lang", language);
            link.href = url.href;
        });
        try {
            localStorage.setItem(storageKey, language);
        } catch {
            // Navigation links retain the language when browser storage is unavailable.
        }
    }

    let savedLanguage;
    try {
        savedLanguage = localStorage.getItem(storageKey);
    } catch {
        // English remains the default when browser storage is unavailable.
    }
    const requestedLanguage = new URL(window.location.href).searchParams.get("lang");
    const initialLanguage = [requestedLanguage, savedLanguage, "en"].find(supported);
    applyLanguage(initialLanguage);
    switcher.hidden = false;
    buttons.forEach(button => {
        button.addEventListener("click", () => {
            const language = button.dataset.language;
            applyLanguage(language);
            const url = new URL(window.location.href);
            url.searchParams.set("lang", language);
            window.history.replaceState(null, "", url.href);
        });
    });
